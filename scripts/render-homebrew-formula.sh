#!/usr/bin/env bash
#
# Write the Homebrew formula for one release to stdout. The release workflow attaches the result to
# the GitHub release and commits it to the tap (kahunakv/homebrew-tap) as Formula/kahuna.rb, so users
# install with:
#
#   brew install kahunakv/tap/kahuna
#
# The formula downloads the prebuilt self-contained archives that scripts/package-release.sh builds;
# Homebrew compiles nothing. It reads each archive's checksum from the .sha256 file beside it, so all
# four platform archives must be in <archive-dir>.
#
# Usage:
#   scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url] > kahuna.rb
#
# base-url defaults to the GitHub release download URL for tag v<version>. A local test passes a
# file:// URL instead.
#
# The installed service keeps its storage and write-ahead log under $(brew --prefix)/var/kahuna,
# through KAHUNA_HOME, because a launchd/systemd service must not depend on the files in one user's
# home directory. A node started by hand from a shell still uses ~/.local/share/kahuna as usual.

set -euo pipefail

VERSION="${1:?usage: scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url]}"
ARCHIVE_DIR="${2:?usage: scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url]}"
BASE_URL="${3:-https://github.com/kahunakv/kahuna/releases/download/v$VERSION}"

sha_of() {
  local file="$ARCHIVE_DIR/kahuna-$VERSION-$1.tar.gz.sha256"
  if [[ ! -f "$file" ]]; then
    echo "error: $file is missing" >&2
    exit 1
  fi
  awk '{ print $1 }' "$file"
}

SHA_OSX_ARM64="$(sha_of osx-arm64)"
SHA_OSX_X64="$(sha_of osx-x64)"
SHA_LINUX_ARM64="$(sha_of linux-arm64)"
SHA_LINUX_X64="$(sha_of linux-x64)"

cat <<RUBY
# This file is generated by scripts/render-homebrew-formula.sh in kahunakv/kahuna.
# Do not edit it in the tap: the next release overwrites it.
class Kahuna < Formula
  desc "Distributed key-value store, lock manager and sequencer, with its command-line client"
  homepage "https://github.com/kahunakv/kahuna"
  # Explicit, because Homebrew can read the "64" in "...-osx-arm64.tar.gz" as the version.
  version "$VERSION"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "$BASE_URL/kahuna-$VERSION-osx-arm64.tar.gz"
      sha256 "$SHA_OSX_ARM64"
    end
    on_intel do
      url "$BASE_URL/kahuna-$VERSION-osx-x64.tar.gz"
      sha256 "$SHA_OSX_X64"
    end
  end

  on_linux do
    on_arm do
      url "$BASE_URL/kahuna-$VERSION-linux-arm64.tar.gz"
      sha256 "$SHA_LINUX_ARM64"
    end
    on_intel do
      url "$BASE_URL/kahuna-$VERSION-linux-x64.tar.gz"
      sha256 "$SHA_LINUX_X64"
    end
  end

  def install
    libexec.install Dir["*"]
    # The .NET host resolves each symlink to find the runtime and the assemblies beside it. The names
    # match the commands of the .NET global tools.
    bin.install_symlink libexec/"server/Kahuna.Server" => "kahuna-server"
    bin.install_symlink libexec/"cli/Kahuna.Control" => "kahuna-cli"
  end

  def caveats
    <<~EOS
      The service stores its data in #{var}/kahuna/data and its write-ahead log in #{var}/kahuna/wal.
      It serves REST and gRPC on port 8081, and gRPC over cleartext HTTP/2 on port 8083.
      The service starts a standalone node with the default options.

      A node started by hand with \`kahuna-server\` stores its files in ~/.local/share/kahuna instead.
      Run \`kahuna-server --help\` for the options.

      \`kahuna-cli\` connects to http://127.0.0.1:8083 by default, which is the service.
    EOS
  end

  service do
    run [opt_bin/"kahuna-server"]
    environment_variables KAHUNA_HOME: var/"kahuna"
    keep_alive true
    log_path var/"log/kahuna.log"
    error_log_path var/"log/kahuna.log"
  end

  test do
    # The command-line parser writes the version to stderr, after the banner on stdout.
    assert_match version.to_s, shell_output("#{bin}/kahuna-server --version 2>&1")
    assert_match version.to_s, shell_output("#{bin}/kahuna-cli --version 2>&1")
  end
end
RUBY
